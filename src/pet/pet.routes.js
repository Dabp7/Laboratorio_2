import {Router} from 'express';
import {savePet,updatePet,getPets,searchPet,deletePet} from './pet.controller.js';
import {validateJWT} from '../middlewares/validate-jwt.js';
const router=Router();
router.use(validateJWT);
router.post('/addPet',savePet);
router.get('/findPet/:id',searchPet);
router.get('/',getPets);
router.put('/updatePet/:id',updatePet);
router.delete('/deletePet/:id',deletePet);
export default router;
